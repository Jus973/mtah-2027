"""Board #59: the ball-side degradation targets measured on EXTERNAL automatic tracking only.

    python scripts/external_targets.py MET-G1N MET-G2N > configs/sim_external.yaml

Reads the Metrica Sample Games' native builds (make metrica-sim FAMILY=csv NATIVE=1: the vendor's
own ball loss, no simulated loss), pools their label-free statistics and prints a config that
inherits sim.yaml and replaces every ball-side number fitted on the provided match: the four ball
targets, the gap-onset hazard table and the gap-length histogram. The player side (p11 target,
tracklet and team-wide run tables) stays sim.yaml's: the sample games carry no tracker dropout
to measure it from. No match-bundle access.
"""

import sys
import warnings

import numpy as np

from mtah import config, registry
from mtah.io.atd import load_game
from mtah.learn import stats

mcfg = config.load("sim.yaml")["measure"]
hazard, gap_hist, n_graded, n_missing, lengths, v_seen, v_missing = None, None, 0, 0, [], [], []
for game in sys.argv[1:]:
    sp = registry.spec(game)
    graded = registry.graded_mask(sp)
    atd, _ = load_game(game)
    players, ball = atd.players_m()[..., :2].astype(np.float64), atd.ball_m()
    s = stats.atd_stats(players, ball, atd.team_of_slot, graded, atd.pitch, mcfg, sp["fps"])
    h = np.asarray(s["hazard"], dtype=int)          # (inside/edge, speed, crowd, [seen, onsets])
    hazard = h if hazard is None else hazard + h
    g = np.asarray(s["gap_hist"], dtype=int).sum(axis=0)
    gap_hist = g if gap_hist is None else gap_hist + g
    # The four fit targets, defined exactly as scripts/fit_sim.py ball_summary measures the sims.
    missing = ~np.isfinite(ball[:, 0])
    starts, lens = stats.runs(graded & missing)
    keep = starts > 0
    keep[keep] = graded[starts[keep] - 1] & ~missing[starts[keep] - 1]
    lengths += lens[keep].tolist()
    n_graded += int(graded.sum())
    n_missing += int((missing & graded).sum())
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        v = np.full(players.shape[:2], np.nan)
        v[1:] = np.linalg.norm(np.diff(players, axis=0), axis=-1) * sp["fps"]
        speed = np.nanmean(v, axis=1)
    ok = np.isfinite(speed) & graded
    v_seen += speed[ok & ~missing].tolist()
    v_missing += speed[ok & missing].tolist()

print("# Board #59: external-only ball-side recipe (generated by scripts/external_targets.py from")
print("# {}; Metrica Sample Games native tracking). Player side inherited from sim.yaml.".format(
    ", ".join(sys.argv[1:])))
print("inherit: sim.yaml")
print("targets:")
print("  ball_missing_frac: {:.4f}".format(n_missing / n_graded))
print("  gaps_per_frame: {:.6f}           # {} gaps / {} graded frames".format(
    len(lengths) / n_graded, len(lengths), n_graded))
print("  gap_median_frames: {:.0f}".format(np.median(lengths)))
print("  collective_speed_ratio: {:.3f}".format(np.median(v_missing) / np.median(v_seen)))
print("degrade:")
print("  hazard:")
for e, side in enumerate(("inside", "edge")):
    print("    {}:".format(side))
    for row in hazard[e].tolist():
        print("      - {}".format(row))
print("  gap_length_hist: {}".format(gap_hist.tolist()))
